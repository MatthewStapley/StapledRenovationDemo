// ---------------------------------------------------------------------------
// URL helpers. The demo is served from a sub-path on GitHub Pages
// (/StapledRenovationDemo/), so every internal link and asset URL must go
// through `asset()` rather than starting with a bare "/".
// ---------------------------------------------------------------------------

const BASE = import.meta.env.BASE_URL.replace(/\/?$/, "/");

/** Prefix a site-root path ("/images/x.webp", "/bathroom/") with the base. */
export const asset = (path: string) => BASE + path.replace(/^\//, "");

export interface ResponsiveImage {
  src: string;
  srcset: string;
  width: number;
  height: number;
}

/**
 * A responsive image generated by scripts/fetch-images.py, which writes
 * public/images/<name>-<width>.webp for each width. `src` (the fallback for
 * browsers without srcset) is the second-largest size.
 */
export function responsive(name: string, widths: number[], ratio: number): ResponsiveImage {
  const url = (w: number) => asset(`/images/${name}-${w}.webp`);
  const largest = widths[widths.length - 1];
  return {
    src: url(widths[Math.max(0, widths.length - 2)]),
    srcset: widths.map((w) => `${url(w)} ${w}w`).join(", "),
    width: largest,
    height: Math.round(largest * ratio),
  };
}
